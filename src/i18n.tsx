const compiled = PATTERNS.map((p) => {
  const names: string[] = [];
  const src = p.ru
    .split(/(\{\w+\})/)
    .map((part) => {
      const m = part.match(/^\{(\w+)\}$/);
      if (m) {
        names.push(m[1]);
        return "(.+?)";
      }
      return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    })
    .join("");
  return { re: new RegExp("^" + src + "$"), names, en: p.en, kk: p.kk };
});

function fill(template: string, names: string[], values: string[]) {
  let out = template;
  names.forEach((n, i) => {
    out = out.split("{" + n + "}").join(translateCore(values[i]) ?? values[i]);
  });
  return out;
}

function translateCore(core: string): string | null {
  const hit = DICT[core];
  if (hit) return lang === "en" ? hit[0] : hit[1];
  for (const p of compiled) {
    const m = core.match(p.re);
    if (m) return fill(lang === "en" ? p.en : p.kk, p.names, m.slice(1));
  }
  return null;
}

export function tr(text: string): string {
  if (lang === "ru" || !text || !CYR.test(text)) return text;
  const lead = text.match(/^\s*/)![0];
  const trail = text.match(/\s*$/)![0];
  const core = text.trim();
  const out = translateCore(core);
  return out == null ? text : lead + out + trail;
}

const originals = new WeakMap<Node, string>();
const applied = new WeakMap<Node, string>();
const ATTRS = ["placeholder", "title", "aria-label"];
const attrOriginals = new WeakMap<Element, Record<string, string>>();
const attrApplied = new WeakMap<Element, Record<string, string>>();

function skip(node: Node) {
  const el = node.nodeType === Node.ELEMENT_NODE ? (node as Element) : node.parentElement;
  return !!el && !!el.closest('[translate="no"]');
}

function handleText(node: Node) {
  if (skip(node)) return;
  const current = node.nodeValue || "";
  if (applied.get(node) !== current) originals.set(node, current);
  const original = originals.get(node) || "";
  if (!CYR.test(original)) return;
  const next = tr(original);
  applied.set(node, next);
  if (node.nodeValue !== next) node.nodeValue = next;
}

function handleAttr(el: Element, name: string) {
  const current = el.getAttribute(name);
  if (current == null) return;
  const orig = attrOriginals.get(el) || {};
  const app = attrApplied.get(el) || {};
  if (app[name] !== current) orig[name] = current;
  attrOriginals.set(el, orig);
  if (!CYR.test(orig[name] || "")) return;
  const next = tr(orig[name]);
  app[name] = next;
  attrApplied.set(el, app);
  if (current !== next) el.setAttribute(name, next);
}

function walk(root: Node) {
  if (root.nodeType === Node.TEXT_NODE) return handleText(root);
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const el = root as Element;
  if (el.tagName === "SCRIPT" || el.tagName === "STYLE") return;
  ATTRS.forEach((a) => el.hasAttribute(a) && handleAttr(el, a));
  const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n = walker.nextNode();
  while (n) {
    if (n.nodeType === Node.TEXT_NODE) handleText(n);
    else ATTRS.forEach((a) => (n as Element).hasAttribute(a) && handleAttr(n as Element, a));
    n = walker.nextNode();
  }
}

function retranslateAll() {
  if (document.body) walk(document.body);
  const t = originals.get(document as any) || document.title;
  originals.set(document as any, t);
  document.title = tr(t);
}

